<#
.SYNOPSIS
  Renders the logo files and the brand book from the SVG sources with headless Microsoft Edge:
  brand/logo/*.png (transparent, 512 and 2048 px wide), brand/logo/*.jpg (white background, 2048 px),
  brand/logo/logo.pdf (all variants, vector) and brand/ksiega-znaku.pdf (A4 landscape).

.DESCRIPTION
  The SVG sources in brand/src are generated by brand/tools/generate_svg.py. The outputs are committed.
  ASCII only, like site/build.ps1. Pattern: site/og.ps1.

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File brand/build.ps1
#>

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$Root = $PSScriptRoot
$Src = Join-Path $Root 'src'
$Out = Join-Path $Root 'logo'
$Tmp = Join-Path ([System.IO.Path]::GetTempPath()) ('brand-' + [guid]::NewGuid())
New-Item -ItemType Directory -Force $Out, $Tmp | Out-Null

$Edge = @(
    "${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe",
    "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe"
) | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $Edge) { throw 'Microsoft Edge not found.' }

# Logo variants rendered to raster files (the favicon only goes to the site).
$Variants = 'sygnet', 'sygnet-bez-tla', 'logo-poziome', 'logo-pionowe', 'logo-z-haslem', 'logo-mono-czarne', 'logo-mono-biale'

function Invoke-Edge([string[]]$EdgeArgs, [string]$Result) {
    $profileDir = Join-Path $Tmp ('edge-' + [guid]::NewGuid())
    $all = @('--headless=new', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1',
        '--allow-file-access-from-files', "--user-data-dir=$profileDir") + $EdgeArgs
    $p = Start-Process -FilePath $Edge -ArgumentList $all -Wait -PassThru -WindowStyle Hidden
    if ($p.ExitCode -ne 0 -or -not (Test-Path $Result)) { throw "Edge failed: $Result" }
}

function Get-ViewBox([string]$File) {
    $svg = [xml](Get-Content -Raw -Encoding UTF8 $File)
    $vb = $svg.svg.viewBox -split '\s+' | ForEach-Object { [double]::Parse($_, [Globalization.CultureInfo]::InvariantCulture) }
    return @($vb[2], $vb[3])
}

function Get-FileUri([string]$Path) { return ([System.Uri]$Path).AbsoluteUri }

foreach ($name in $Variants) {
    $svgPath = Join-Path $Src "$name.svg"
    $vb = Get-ViewBox $svgPath
    # The white variant is shown on navy in the JPG (a white logo on white would be invisible).
    $jpgBg = if ($name -eq 'logo-mono-biale') { '#0B1F3A' } else { '#FFFFFF' }

    foreach ($width in 512, 2048) {
        $height = [int][Math]::Ceiling($width * $vb[1] / $vb[0])
        $html = Join-Path $Tmp "$name-$width.html"
        Set-Content -Encoding UTF8 $html ("<!doctype html><meta charset='utf-8'><style>html,body{margin:0;background:transparent}" +
            "img{display:block;width:${width}px;height:${height}px}</style><img src='$(Get-FileUri $svgPath)'>")
        $png = Join-Path $Out "$name-$width.png"
        Invoke-Edge @('--default-background-color=00000000', "--window-size=$width,$height", "--screenshot=$png", (Get-FileUri $html)) $png
        Write-Output "brand/logo/$name-$width.png"

        if ($width -eq 2048) {
            # JPG has no transparency: draw the PNG on a solid background.
            $image = [System.Drawing.Image]::FromFile($png)
            try {
                $bitmap = New-Object System.Drawing.Bitmap $image.Width, $image.Height
                $g = [System.Drawing.Graphics]::FromImage($bitmap)
                $g.Clear([System.Drawing.ColorTranslator]::FromHtml($jpgBg))
                $g.DrawImage($image, 0, 0, $image.Width, $image.Height)
                $g.Dispose()
                $codec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object { $_.MimeType -eq 'image/jpeg' }
                $params = New-Object System.Drawing.Imaging.EncoderParameters 1
                $params.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter ([System.Drawing.Imaging.Encoder]::Quality), 95L
                $bitmap.Save((Join-Path $Out "$name.jpg"), $codec, $params)
                $bitmap.Dispose()
            }
            finally { $image.Dispose() }
            Write-Output "brand/logo/$name.jpg"
        }
    }
}

# logo.pdf: one A4 landscape page per variant, vector (the SVG stays vector when printed).
$pages = foreach ($name in $Variants) {
    $bg = if ($name -eq 'logo-mono-biale') { '#0B1F3A' } else { '#FFFFFF' }
    "<section style='background:$bg'><img src='$(Get-FileUri (Join-Path $Src "$name.svg"))'><p style='color:$(if ($bg -eq '#FFFFFF') { '#3D4F6A' } else { '#CBD5E1' })'>$name.svg</p></section>"
}
$logoHtml = Join-Path $Tmp 'logo-pdf.html'
Set-Content -Encoding UTF8 $logoHtml ("<!doctype html><meta charset='utf-8'><style>@page{size:297mm 210mm;margin:0}" +
    "html,body{margin:0}body{-webkit-print-color-adjust:exact;print-color-adjust:exact;font:10pt Arial,sans-serif}" +
    "section{width:297mm;height:210mm;display:flex;flex-direction:column;align-items:center;justify-content:center;page-break-after:always}" +
    "section:last-child{page-break-after:auto}img{max-width:200mm;max-height:110mm;width:200mm}</style>" + ($pages -join ''))
$logoPdf = Join-Path $Out 'logo.pdf'
Invoke-Edge @('--no-pdf-header-footer', "--print-to-pdf=$logoPdf", (Get-FileUri $logoHtml)) $logoPdf
Write-Output 'brand/logo/logo.pdf'

# Brand book. It loads Inter from Google Fonts, so give the page time to load the font.
$bookPdf = Join-Path $Root 'ksiega-znaku.pdf'
Invoke-Edge @('--no-pdf-header-footer', '--virtual-time-budget=5000', "--print-to-pdf=$bookPdf", (Get-FileUri (Join-Path $Root 'ksiega-znaku.html'))) $bookPdf
Write-Output 'brand/ksiega-znaku.pdf'

# Site: the sygnet in the header and as the favicon, and the downloads on the "Materialy" page.
$Site = Join-Path (Split-Path $Root -Parent) 'site/public/assets'
$SiteBrand = Join-Path $Site 'brand'
New-Item -ItemType Directory -Force $SiteBrand | Out-Null
Copy-Item (Join-Path $Src 'sygnet.svg') (Join-Path $Site 'logo.svg') -Force
Copy-Item (Join-Path $Src 'favicon.svg') (Join-Path $Site 'favicon.svg') -Force
Copy-Item $bookPdf (Join-Path $SiteBrand 'aed-radar-ksiega-znaku.pdf') -Force
$zip = Join-Path $SiteBrand 'aed-radar-logo.zip'
Remove-Item $zip -ErrorAction SilentlyContinue
$stage = Join-Path $Tmp 'aed-radar-logo'
New-Item -ItemType Directory -Force (Join-Path $stage 'svg'), (Join-Path $stage 'png'), (Join-Path $stage 'jpg'), (Join-Path $stage 'pdf') | Out-Null
Get-ChildItem $Src -Filter *.svg | Where-Object { $_.Name -ne 'favicon.svg' } | Copy-Item -Destination (Join-Path $stage 'svg')
Get-ChildItem $Out -Filter *.png | Copy-Item -Destination (Join-Path $stage 'png')
Get-ChildItem $Out -Filter *.jpg | Copy-Item -Destination (Join-Path $stage 'jpg')
Copy-Item (Join-Path $Out 'logo.pdf') (Join-Path $stage 'pdf')
Copy-Item $bookPdf (Join-Path $stage 'pdf/ksiega-znaku.pdf')
Compress-Archive -Path (Join-Path $stage '*') -DestinationPath $zip
Write-Output 'site/public/assets/logo.svg, favicon.svg, brand/aed-radar-ksiega-znaku.pdf, brand/aed-radar-logo.zip'

Remove-Item -Recurse -Force $Tmp -ErrorAction SilentlyContinue
